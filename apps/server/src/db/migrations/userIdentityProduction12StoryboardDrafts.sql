CREATE TABLE IF NOT EXISTS production_storyboard_drafts (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  project_id VARCHAR(36) NOT NULL,
  episode_id VARCHAR(36) NOT NULL,
  source_script_revision INT UNSIGNED NOT NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  status ENUM('pending', 'confirmed') NOT NULL DEFAULT 'pending',
  provider_id VARCHAR(100) NOT NULL,
  model_id VARCHAR(200) NOT NULL,
  team_version VARCHAR(64) NOT NULL,
  skill_version VARCHAR(72) NOT NULL,
  draft JSON NOT NULL,
  created_by VARCHAR(36) NOT NULL,
  updated_by VARCHAR(36) NOT NULL,
  confirmed_at DATETIME NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY production_storyboard_draft_project_episode_unique (project_id, episode_id),
  KEY production_storyboard_draft_creator_index (created_by, created_at),
  CONSTRAINT production_storyboard_draft_project_fk FOREIGN KEY (project_id) REFERENCES production_projects(id) ON DELETE CASCADE,
  CONSTRAINT production_storyboard_draft_episode_fk FOREIGN KEY (episode_id) REFERENCES production_episodes(id) ON DELETE CASCADE,
  CONSTRAINT production_storyboard_draft_creator_fk FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT production_storyboard_draft_updater_fk FOREIGN KEY (updated_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
