CREATE TABLE generation_usage_daily (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  day VARCHAR(10) NOT NULL,
  user_id VARCHAR(36) NOT NULL,
  directory_hash CHAR(64) NOT NULL,
  workspace_name VARCHAR(255) NOT NULL,
  provider_id VARCHAR(100) NOT NULL,
  model_id VARCHAR(200) NOT NULL,
  media_type ENUM('text','image','video','audio') NOT NULL,
  video_billing_kind VARCHAR(32) NOT NULL DEFAULT 'none',
  request_count INT UNSIGNED NOT NULL DEFAULT 0,
  success_count INT UNSIGNED NOT NULL DEFAULT 0,
  failed_count INT UNSIGNED NOT NULL DEFAULT 0,
  output_count INT UNSIGNED NOT NULL DEFAULT 0,
  units DECIMAL(26,6) UNSIGNED NOT NULL DEFAULT 0,
  captured_credits DECIMAL(26,6) UNSIGNED NOT NULL DEFAULT 0,
  billable_input_tokens DECIMAL(26,0) UNSIGNED NOT NULL DEFAULT 0,
  output_tokens DECIMAL(26,0) UNSIGNED NOT NULL DEFAULT 0,
  video_seconds DECIMAL(26,6) UNSIGNED NOT NULL DEFAULT 0,
  pending_count INT UNSIGNED NOT NULL DEFAULT 0,
  usable_count INT UNSIGNED NOT NULL DEFAULT 0,
  waste_count INT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY generation_usage_daily_unique (day, user_id, directory_hash, provider_id, model_id, media_type, video_billing_kind),
  KEY generation_usage_daily_user_index (user_id, day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE generation_outputs (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  job_id VARCHAR(36) NOT NULL,
  user_id VARCHAR(36) NOT NULL,
  output_index INT UNSIGNED NOT NULL,
  media_type ENUM('text','image','video','audio') NOT NULL,
  status ENUM('pending','usable','waste') NOT NULL DEFAULT 'pending',
  waste_reason VARCHAR(500),
  output_snapshot JSON NOT NULL,
  reviewed_by VARCHAR(36),
  reviewed_at DATETIME,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  UNIQUE KEY generation_output_job_index_unique (job_id, output_index),
  KEY generation_output_user_status_index (user_id, status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
