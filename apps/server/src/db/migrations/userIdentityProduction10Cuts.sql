CREATE TABLE IF NOT EXISTS production_cuts (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  project_id VARCHAR(36) NOT NULL,
  episode_id VARCHAR(36) NULL,
  version INT UNSIGNED NOT NULL,
  title VARCHAR(200) NOT NULL,
  status ENUM('review', 'changesRequested', 'approved', 'delivered') NOT NULL DEFAULT 'review',
  video_path VARCHAR(255) NOT NULL,
  project_path VARCHAR(255) NOT NULL,
  manifest_path VARCHAR(255) NOT NULL,
  file_hash CHAR(64) NOT NULL,
  file_size BIGINT UNSIGNED NOT NULL,
  duration_ms BIGINT UNSIGNED NOT NULL,
  width INT UNSIGNED NOT NULL,
  height INT UNSIGNED NOT NULL,
  frame_rate VARCHAR(32) NOT NULL,
  mime_type VARCHAR(120) NOT NULL,
  metadata JSON NOT NULL,
  created_by VARCHAR(36) NOT NULL,
  comment TEXT NULL,
  reviewed_by VARCHAR(36) NULL,
  reviewed_at DATETIME NULL,
  delivered_by VARCHAR(36) NULL,
  delivered_at DATETIME NULL,
  created_at DATETIME NOT NULL,
  updated_at DATETIME NOT NULL,
  KEY production_cut_project_index (project_id, created_at),
  KEY production_cut_episode_version_index (project_id, episode_id, version),
  CONSTRAINT production_cut_project_fk FOREIGN KEY (project_id) REFERENCES production_projects(id) ON DELETE CASCADE,
  CONSTRAINT production_cut_episode_fk FOREIGN KEY (episode_id) REFERENCES production_episodes(id),
  CONSTRAINT production_cut_creator_fk FOREIGN KEY (created_by) REFERENCES users(id),
  CONSTRAINT production_cut_reviewer_fk FOREIGN KEY (reviewed_by) REFERENCES users(id),
  CONSTRAINT production_cut_deliverer_fk FOREIGN KEY (delivered_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
